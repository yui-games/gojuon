function normalize(str){
  let out='',bad=[];
  for(let ch of String(str||'').normalize('NFC')){
    const code=ch.charCodeAt(0);
    if(code>=0x30A1&&code<=0x30F6)ch=String.fromCharCode(code-0x60);
    if(code===0x3099||code===0x309A)continue;
    if(DROP.has(ch))continue;
    if(LONG.has(ch))ch='ー';
    if(MAP[ch])ch=MAP[ch];
    if(CELL_OF[ch])out+=ch;else bad.push(ch);
  }
  return {kana:out,bad};
}

